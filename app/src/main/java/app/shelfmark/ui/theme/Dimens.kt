package app.shelfmark.ui.theme

import androidx.compose.ui.unit.dp

/** The spacing every screen shares, so they line up with each other. */
object Dimens {
    /** Left and right margin of every screen and sheet. */
    val gutter = 20.dp

    /** Space between a top bar and the first content. */
    val topGap = 8.dp

    /** Space after the last content, above the navigation bar. */
    val bottomGap = 32.dp

    /** Between the sections of a page (notes, details, series …). */
    val sectionGap = 36.dp

    /** From a section's heading to its content, and between cards in one group. */
    val headerGap = 12.dp

    /** Inside cards. */
    val cardPadding = 16.dp

    /** Full-width buttons. */
    val buttonHeight = 52.dp
}
